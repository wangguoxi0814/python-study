# 06_字符串类型（str）
#
# 字符串用来表示文本，是 Python 里常用的数据类型之一（还有数字、布尔等）。
# 建议按下面顺序阅读：先会「怎么写」→ 再会「怎么用」→ 最后理解「有什么性质」。
#
# ---------------------------------------------------------------------------
# 一、怎么创建字符串
# ---------------------------------------------------------------------------


print('==============================')
print('1. 单引号与双引号（效果相同，任选一种习惯即可）')
single_quoted = 'hello'
double_quoted = "world"
print('单引号:', single_quoted)
print('双引号:', double_quoted)

print('==============================')
print('2. 转义字符：用 \\n 表示换行（还有更多转义，遇到再查即可）')
with_newline = "hello\nworld"
print('直接打印（会真的换行）:', with_newline)
print('用 repr 看「里面到底有什么」:', repr(with_newline))

print('==============================')
print('3. 多行字符串：三引号，换行按你写的来，不必手写 \\n')
triple_single = '''
    hello
    python'''
triple_double = """
hello
world"""
print('三单引号多行:', repr(triple_single))
print('三双引号多行:', repr(triple_double))

# ---------------------------------------------------------------------------
# 二、拼接与格式化（把多个字符串组合成一句）
# ---------------------------------------------------------------------------

print('==============================')
print('4. 用 + 拼接（注意：数字要先 str() 再拼，否则会类型错误）')
a = 'hello'
b = 'world'
print('a + b:', a + b)
print('和数字拼接:', '数量=' + str(3))

print('==============================')
print('5. 格式化：% 占位符（老写法，能读懂别人代码即可）')
x, y = 'hello', 'world'
print('%s %s' % (x, y))

print('==============================')
print('6. 格式化：f-string（推荐，直观）')
name = 'Python'
version = 3.10
# 这里version是浮点类型，python默认会自动省去无意义的0，因此3.10会显示为3.1
print(f'你好 {name}! 版本提示：{name} {version}')
# 这里.2f表示保留2位小数，如果小数位数不足2位，则补0
print(f'你好 {name}! 版本提示：{name} {version:.2f}')
# 或者直接将version声明为字符串
version = "3.10"
print(f'你好 {name}! 版本提示：{name} {version}')

# ---------------------------------------------------------------------------
# 三、长度与类型
# ---------------------------------------------------------------------------

print('==============================')
print('7. len()：字符个数（空格、换行都算 1 个字符）')
print('len("hello"):', len('hello'))
print('len("hello world"):', len('hello world'))
s = 'hello\npython'
print('len(含换行):', len(s), '  repr:', repr(s))

multi = '''
    hello
    python
'''
print('多行字符串 len:', len(multi))
print('多行 repr（便于数换行、空格）:', repr(multi))

print('==============================')
print('8. type()：查看类型')
print(type('hello'), type(multi))

# ---------------------------------------------------------------------------
# 四、重要性质：不可变 + 是序列（可下标、可切片）
# ---------------------------------------------------------------------------

print('==============================')
print('9. 不可变：不能通过 s[0] = "x" 改某一个字符（会报错）')
s = 'hello'
print('s:', s)
# 想「改」内容：用拼接/切片生成新字符串，例如：
s2 = 'H' + s[1:]
print('得到新串:', s2)
# s[0] = 'H'  # 取消注释运行会看到 TypeError

print('==============================')
print('10. 下标索引：正数从 0 开始，负数从末尾数')
#   H   e   l   l   o
#   0   1   2   3   4
#  -5  -4  -3  -2  -1
s = 'hello'
print('s[0], s[-1]:', s[0], s[-1])
print('查找子串首次出现位置（找不到会报错）:', s.index('e'), s.index('o'))
print('最后一个 o 的「等价负索引」:', s.index('o') - len(s))

print('==============================')
print('11. 切片 s[start:end]：左闭右开，省略表示从头或到尾')
print('s[1:3]  →', s[1:3])
print('s[1:]   →', s[1:])
print('s[-3:-1]→', s[-3:-1])
print('s[-3:]  →', s[-3:])

# ---------------------------------------------------------------------------
# 五、遍历、哈希、比较（了解即可，后面会反复用到）
# ---------------------------------------------------------------------------

print('==============================')
print('12. 可迭代：用 for 逐个字符遍历')
for ch in 'hello':
    print(ch, end=' ')
print()

print('==============================')
print('13. 可哈希：可作为 dict 的键、可放进 set（依赖「不可变」）')
print('hash("hello"):', hash('hello'))
# 说明：内容相同的字符串在同一运行过程里 hash 相同；不同内容理论上可能出现哈希碰撞（极少遇到）。

print('==============================')
print('14. 比较：== / != 看内容是否相同；< > 按「字典序」比编码值')
print('内容相等:', 'hello' == 'hello', 'hello' != 'world')

print('字典序（英文按 ASCII/Unicode 码点，从左到右比，先分出大小就结束）:')
print("'a' < 'b':", 'a' < 'b')
print("'ac' < 'ab':", 'ac' < 'ab')  # 第二位 c > b
print("'abc' < 'abd':", 'abc' < 'abd')
print("'acd' < 'abc':", 'acd' < 'abc')  # 第二位 c > b
print("'abc' < 'abcd':", 'abc' < 'abcd')  # 前面都一样，短的更小
print("'abcd' < 'afc':", 'abcd' < 'afc')  # 第二位 b < f，在这里就定了，不必比到第三位
