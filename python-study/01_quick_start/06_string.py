# ---------------------------------------------------------------------------
# 五、重要性质：不可变 + 是序列（可下标、可切片）
# ---------------------------------------------------------------------------

print('==============================')
print('9. 不可变：不能通过 s[0] = "x" 改某一个字符（会报错）')
s = 'hello'
print('s:', s)
# 想「改」内容：用拼接/切片生成新字符串，例如：
s2 = 'H' + s[1:]
print('得到新串:', s2)
# s[0] = 'H'  # 取消注释运行会看到 TypeError

print('==============================')
print('10. 下标索引：正数从 0 开始，负数从末尾数')
#   H   e   l   l   o
#   0   1   2   3   4
#  -5  -4  -3  -2  -1
s = 'hello'
print('s[0], s[-1]:', s[0], s[-1])
print('查找子串首次出现位置（找不到会报错）:', s.index('e'), s.index('o'))
# print('查找不存在的字符会报错：', s.index('z'))
print('最后一个 o 的「等价负索引」:', s.index('o') - len(s))

print('==============================')
print('11. 切片 s[start:end]：左闭右开，省略表示从头或到尾')
print('s[1:3]  →', s[1:3])  # el
print('s[1:]   →', s[1:])   # ello
print('s[:2] = ', s[:2])    # he
print('s[-3:-1]→', s[-3:-1]) # ll
print('s[-3:]  →', s[-3:])   # llo
print('11. 切片 s[start:end:step]：左闭右开，按指定步长切片')
print('s[1:4:2] →', s[1:4:2]) # el
print('s[0::2] →', s[0::2])   # hlo

# ---------------------------------------------------------------------------
# 五、遍历、哈希、比较（了解即可，后面会反复用到）
# ---------------------------------------------------------------------------

print('==============================')
print('12. 可迭代：用 for 逐个字符遍历')
for ch in 'hello':
    print(ch, end=' ')
print()

print('==============================')
print('13. 可哈希：可作为 dict 的键、可放进 set（依赖「不可变」）')
print('hash("hello"):', hash('hello'))
# 说明：内容相同的字符串在同一运行过程里 hash 相同；不同内容理论上可能出现哈希碰撞（极少遇到）。

print('==============================')
print('14. 比较：== / != 看内容是否相同；< > 按「字典序」比编码值')
print('内容相等:', 'hello' == 'hello', 'hello' != 'world')

print('字典序（英文按 ASCII/Unicode 码点，从左到右比，先分出大小就结束）:')
print("'a' < 'b':", 'a' < 'b')
print("'ac' < 'ab':", 'ac' < 'ab')  # 第二位 c > b
print("'abc' < 'abd':", 'abc' < 'abd')
print("'acd' < 'abc':", 'acd' < 'abc')  # 第二位 c > b
print("'abc' < 'abcd':", 'abc' < 'abcd')  # 前面都一样，短的更小
print("'abcd' < 'afc':", 'abcd' < 'afc')  # 第二位 b < f，在这里就定了，不必比到第三位
